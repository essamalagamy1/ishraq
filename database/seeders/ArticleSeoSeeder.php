<ul>
<li>استخدم defer أو async لسكريبتات الطرف الثالث</li>
<li>حمّل Analytics بعد أول تفاعل من المستخدم</li>
</ul>

<h3>7. الخطوط المحسّنة</h3>
<ul>
<li>استخدم font-display: swap لإظهار النص فوراً</li>
<li>حمّل فقط الأوزان والأنماط المستخدمة</li>
<li>استخدم preconnect لخوادم الخطوط</li>
</ul>

<h3>8. ضغط Gzip / Brotli</h3>
<p>تفعيل الضغط على الخادم يقلل حجم الملفات المنقولة بنسبة 60-80%.</p>

